void PreCond(bool isInverse, int M_, int N_, std::vector<double>* data)
{
    std::vector<double>* la_;
    std::vector<double>* ra_;

    if (isInverse) {
        la_ = &lia;
        ra_ = &ria;
    } else {
        la_ = &la;
        ra_ = &ra;
    };

    int k = 0;
    int k1 = (M_ * (M_ + 1)) / 2 - 1;
    for (int i = 0; i < M_; ++i) {
        double laa_ = 0;
        double raa_ = 0;
        for (int l = 0; l < M_ - i; ++l) {
            laa_ = laa_ + (*la_)[k] * (*data)[i + l];
            raa_ = raa_ + (*ra_)[k1] * (*data)[N_ - 1 - i - l];
            k++;
            k1--;
        };
        (*data)[i] = laa_;
        (*data)[N_ - 1 - i] = raa_;
    };
}

void fwt01_one_step(int M, int N, std::vector<double>* ain, std::vector<double>* aout)
{
    int Ndiv2 = N / 2;
    int Mm1 = M - 1;
    int M2 = 2 * M;

    for (int k = 0; k < M; ++k) {
        int Index = k * (M + k);
        double SumLh = (*ain)[0] * lh_[Index];
        double SumLg = (*ain)[0] * lg_[Index];
        double SumRh = (*ain)[N - 1] * rh_[Index];
        double SumRg = (*ain)[N - 1] * rg_[Index];
        for (int j = 1; j <= M + 2 * k; ++j) {
            Index++;
            //--- perform transform at the left } ---------- //
            SumLh = SumLh + (*ain)[j] * lh_[Index];
            SumLg = SumLg + (*ain)[j] * lg_[Index];
            //--- perform transform at the right } ---------- //
            SumRh = SumRh + (*ain)[N - 1 - j] * rh_[Index];
            SumRg = SumRg + (*ain)[N - 1 - j] * rg_[Index];
        };
        (*aout)[k] = SumLh;
        (*aout)[Ndiv2 + k] = SumLg;
        (*aout)[Ndiv2 - k - 1] = SumRh;
        (*aout)[N - 1 - k] = SumRg;
    };
    //-------- original filter ------------------//
    for (int i = M; i < Ndiv2 - M; ++i) {
        int i2m3 = 2 * i - Mm1;
        double SumH = h_[0] * (*ain)[i2m3];
        double SumG = g_[0] * (*ain)[i2m3];
        for (int j = 1; j < M2; ++j) {
            SumH = SumH + h_[j] * (*ain)[i2m3 + j];
            SumG = SumG + g_[j] * (*ain)[i2m3 + j];
        };
        (*aout)[i] = SumH;
        (*aout)[Ndiv2 + i] = SumG;
    };
};

std::vector<double> fwt01(bool Precond, int N_steps, int M, std::vector<float>* data)
{
    std::vector<double> E_(N_steps);

    int NN = data->size();

    std::vector<double> ain(NN);
    std::vector<double> aout(NN);

    for (size_t i = 0; i < NN; ++i) ain[i] = (*data)[i];

    SetWavelet(M);
    if (Precond) PreCond(false, M, NN, &ain);

    for (int l = 0; l < N_steps; ++l) {
        fwt01_one_step(M, NN, &ain, &aout);
        for (int i = 0; i < NN; ++i) ain[i] = aout[i];
        E_[l] = 0;
        for (int i = NN / 2; i < NN; ++i) E_[l] += aout[i] * aout[i];
        NN = NN / 2;
    }
    FreeWavelet();
    ain.clear();
    aout.clear();

    return E_;
}
